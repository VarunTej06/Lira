async function ensureLiraSpace(): Promise<void> {
  const existingLira = await db.spaces.where('key').equalsIgnoreCase('LIRA').first() ||
    await db.spaces.where('name').equalsIgnoreCase('Lira').first();
  let liraSpaceId: number;
  if (!existingLira) {
    liraSpaceId = await db.spaces.add({
      name: 'Lira',
      key: 'LIRA',
      icon: '🎯',
      color: '#0052CC',
      description: 'Lira product roadmap, feature development, and issue tracking',
      createdAt: daysAgo(10),
      updatedAt: now,
    }) as number;
    await seedLiraIssues(liraSpaceId);
  } else {
    liraSpaceId = existingLira.id!;
    const issueCount = await db.issues.where('spaceId').equals(liraSpaceId).count();
    if (issueCount === 0) {
      await seedLiraIssues(liraSpaceId);
    }
  }
}

